import Foundation

// MARK: - Cell Type

enum SokobanCell: Int, Codable, Equatable {
    case floor = 0
    case wall = 1
    case target = 2
    case box = 3
    case boxOnTarget = 4
    case player = 5
    case playerOnTarget = 6
}

// MARK: - Level Model

struct SokobanLevel: Identifiable {
    let id: Int
    let packId: Int
    let grid: [[SokobanCell]]
    let parMoves: Int
    let title: String

    var rows: Int { grid.count }
    var cols: Int { grid[0].count }

    var boxCount: Int {
        grid.flatMap { $0 }.filter { $0 == .box || $0 == .boxOnTarget }.count
    }

    var targetCount: Int {
        grid.flatMap { $0 }.filter { $0 == .target || $0 == .boxOnTarget }.count
    }

    var playerStart: (row: Int, col: Int)? {
        for r in 0..<rows {
            for c in 0..<cols {
                if grid[r][c] == .player || grid[r][c] == .playerOnTarget {
                    return (r, c)
                }
            }
        }
        return nil
    }
}

// MARK: - Helper to build grid

private func G(_ rows: [[Int]]) -> [[SokobanCell]] {
    rows.map { row in row.map { SokobanCell(rawValue: $0)! } }
}


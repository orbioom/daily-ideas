/// Embedded real-English word data, lowercased and deduplicated at load time.
///
/// For each supported length there are two lists:
///   - `answers`: the pool from which the daily / practice solution is chosen
///     (common, well-known words).
///   - `validGuesses`: a strict superset (answers ∪ extra real words) used to
///     accept what the player types. A guess must be in this set to be submitted.
///
/// Every entry is a genuine English word.
enum WordLists {

    /// Supported word lengths.
    static let supportedLengths = [4, 5, 6]

    /// Answer pool for a given length, deduplicated, lowercased, length-filtered.
    static func answers(length: Int) -> [String] {
        switch length {
        case 4: return cleaned(answers4, length: 4)
        case 6: return cleaned(answers6, length: 6)
        default: return cleaned(answers5, length: 5)
        }
    }

    /// Valid-guess set for a given length (answers ∪ extra valid words).
    static func validGuessSet(length: Int) -> Set<String> {
        switch length {
        case 4: return Set(cleaned(answers4, length: 4) + cleaned(extra4, length: 4))
        case 6: return Set(cleaned(answers6, length: 6) + cleaned(extra6, length: 6))
        default: return Set(cleaned(answers5, length: 5) + cleaned(extra5, length: 5))
        }
    }

    /// Whether `word` is an acceptable guess at its length.
    static func isValidGuess(_ word: String, length: Int) -> Bool {
        let w = word.lowercased()
        guard w.count == length else { return false }
        return validGuessSet(length: length).contains(w)
    }

    /// Lowercase, dedupe, and keep only words of exactly `length` characters made
    /// of a–z. This makes the embedded lists self-healing: any stray off-length
    /// word is silently dropped rather than corrupting the pool.
    private static func cleaned(_ words: [String], length: Int) -> [String] {
        var seen = Set<String>()
        var out: [String] = []
        for raw in words {
            let w = raw.lowercased()
            guard w.count == length else { continue }
            guard w.allSatisfy({ $0.isLetter && $0.isASCII }) else { continue }
            if !seen.contains(w) {
                seen.insert(w)
                out.append(w)
            }
        }
        return out
    }


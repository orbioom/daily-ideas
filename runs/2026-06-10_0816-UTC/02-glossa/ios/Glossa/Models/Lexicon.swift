import Foundation

struct LexiconEntry: Identifiable, Hashable {
    let id: String
    let front: String
    let back: String
    let gender: String          // "m" | "f" | "n" | ""
    let exampleTarget: String
    let exampleEnglish: String
}

struct LanguagePack: Identifiable {
    let code: String
    let name: String
    let flag: String
    let entries: [LexiconEntry]
    var id: String { code }
}

/// Built-in starter vocabulary: ~190 of the highest-frequency everyday words
/// per pack family (nouns with articles and gender, core verbs, adjectives,
/// and survival phrases), each with a short example where it helps.
enum Lexicon {

    static let packs: [LanguagePack] = [spanish, french, german]

    static func pack(code: String) -> LanguagePack? {
        packs.first { $0.code == code }
    }

    /// Leading articles per language, used by the relaxed answer checker.
    static func articles(for code: String) -> [String] {
        switch code {
        case "es": return ["el", "la", "los", "las", "un", "una"]
        case "fr": return ["le", "la", "les", "un", "une"]
        case "de": return ["der", "die", "das", "ein", "eine"]
        default: return []
        }
    }

    private static func e(_ code: String, _ i: Int, _ front: String, _ back: String,
                          _ gender: String = "", _ exT: String = "", _ exE: String = "") -> LexiconEntry {
        LexiconEntry(id: "\(code)-\(i)", front: front, back: back, gender: gender,
                     exampleTarget: exT, exampleEnglish: exE)
    }


import Foundation

enum SkillLevel: String, CaseIterable, Identifiable {
    case foundation = "Foundation"
    case manners = "Manners"
    case tricks = "Tricks"
    case advanced = "Advanced"

    var id: String { rawValue }

    var blurb: String {
        switch self {
        case .foundation: return "The first six — everything else builds on these."
        case .manners: return "A dog you can take anywhere."
        case .tricks: return "Pure fun, great for rainy days."
        case .advanced: return "Precision work for graduates."
        }
    }
}


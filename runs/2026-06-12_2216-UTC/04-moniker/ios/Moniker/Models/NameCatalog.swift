import Foundation

enum NameGender: String, CaseIterable, Codable, Identifiable {
    case girl, boy, unisex

    var id: String { rawValue }
    var displayName: String {
        switch self {
        case .girl: return "Girl"
        case .boy: return "Boy"
        case .unisex: return "Unisex"
        }
    }
    var symbol: String {
        switch self {
        case .girl: return "circle.fill"
        case .boy: return "square.fill"
        case .unisex: return "diamond.fill"
        }
    }
}

enum NameStyle: String, CaseIterable, Codable, Identifiable {
    case classic, modern, vintage, nature, biblical, mythic, short, international, strong, gentle

    var id: String { rawValue }
    var displayName: String { rawValue.capitalized }
}

struct NameEntry: Identifiable, Hashable {
    let name: String
    let gender: NameGender
    let origin: String
    let meaning: String
    let styles: [NameStyle]

    var id: String { name + "|" + gender.rawValue }
}


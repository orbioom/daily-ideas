/// The bundled, curated dictionary. A static value array (NOT SwiftData) so the
/// word data ships with the app and never needs migration. At least 150 entries
/// spanning the everyday / SAT / GRE tiers. Every `example` contains its word
/// (case-insensitive) so fill-in-the-blank can blank it reliably.
enum WordBank {

    /// All words, deduplicated by `id` (lowercased word) at load time.
    static let all: [VocabWord] = {
        var seen = Set<String>()
        var result: [VocabWord] = []
        for w in raw where !seen.contains(w.id) {
            seen.insert(w.id)
            result.append(w)
        }
        return result
    }()

    /// Fast lookup by id (lowercased word).
    static let byID: [String: VocabWord] = {
        Dictionary(uniqueKeysWithValues: all.map { ($0.id, $0) })
    }()

    static func word(id: String) -> VocabWord? { byID[id.lowercased()] }

    static func words(in tier: WordTier) -> [VocabWord] { all.filter { $0.tier == tier } }

    /// Every distinct tag, sorted, for the Lexicon filter UI.
    static let allTags: [String] = {
        var set = Set<String>()
        for w in all { for t in w.tags { set.insert(t) } }
        return set.sorted()
    }()

